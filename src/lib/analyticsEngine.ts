// 2. AUTOMATED EXCEL PARSING, FIELD CLEANING & NORMALIZATION
// ----------------------------------------------------------------------
export function normalizeExcelData(rawRows: any[]): RiceTransaction[] {
  if (!Array.isArray(rawRows)) return [];

  return rawRows.map((row: any, index: number) => {
    // 1. Dynamic Header Finding (Normalization)
    const findValue = (keys: string[], defaultVal: any = '') => {
      const matchKey = Object.keys(row).find(k => 
        keys.some(candidate => (k || '').toLowerCase().replace(/[\s\.\-\(\)]/g, '') === (candidate || '').toLowerCase().replace(/[\s\.\-\(\)]/g, ''))
      );
      return matchKey ? row[matchKey] : defaultVal;
    };

    // Extract raw values
    const rawDate = findValue(['date', 'billdate', 'paymentdate'], '');
    const dateFormatted = rawDate ? new Date(rawDate).toISOString().split('T')[0] : new Date().toISOString().split('T')[0];

    const millerName = String(findValue(['millername', 'miller', 'mill', 'millersname'], 'ANNAPURNA RICE & AGRO INDUSTRIES')).trim();
    const rawPlace = String(findValue(['supplierplace', 'millerplace', 'millplace', 'placeoforigin', 'origin', 'supplierlocation', 'place'], '')).trim();
    const rawArea = String(findValue(['buyerareashop', 'buyerarea', 'buyershop', 'shoparea', 'partyarea', 'area', 'shop', 'road', 'buyerlocation'], '')).trim();
    
    // Disambiguate place (supplier origin) vs area (buyer shop area)
    const millerPlace = rawPlace || 'MIRYALGUDA';
    const buyerArea = rawArea || '4TH BLOCK';
    const placeArea = buyerArea || millerPlace;
    const brand = String(findValue(['brand', 'variety', 'item', 'ricebrand'], 'KESHAR KALI')).trim();
    const buyerName = String(findValue(['buyername', 'buyer', 'party', 'customer', 'partyname'], 'V.K FOODS')).trim().toUpperCase();
    
    const numberOfDays = parseInt(findValue(['numberofdays', 'creditdays', 'days', 'term'], '30'), 10) || 30;
    const paymentReceivedDays = parseInt(findValue(['paymentreceiveddays', 'paidday', 'recdays', 'delay'], '0'), 10) || 0;
    const billNumber = String(findValue(['billnumber', 'billno', 'invoice', 'invoiceno', 'bill'], `BILL-${Date.now()}-${index}`)).trim();
    
    const quantity = parseFloat(findValue(['quantityqtls', 'quantity', 'qty', 'qtls', 'volume'], '100')) || 0;
    const rate = parseFloat(findValue(['rate', 'price', 'rateperqtl'], '4000')) || 0;
    
    // Financials
    const amount = parseFloat(findValue(['amount', 'grossamount', 'total'], String(quantity * rate))) || (quantity * rate);
    const loadingCharges = parseFloat(findValue(['loadingcharges', 'lh', 'loading'], '0')) || 0;
    const commission = parseFloat(findValue(['commission', 'cc', 'comm'], '0')) || 0;
    const tds = parseFloat(findValue(['tds', 'tax'], '0')) || 0;
    const shortage = parseFloat(findValue(['shortage', 'loss', 'short'], '0')) || 0;
    const seller = String(findValue(['seller', 'canvassedby', 'broker'], 'Tejas Canvassing')).trim();
    const difference = parseFloat(findValue(['difference', 'diff'], '0')) || 0;

    // Calculate Net Amount if missing: Net = Amount + Loading - Commission - TDS - Shortage
    const netAmount = parseFloat(findValue(['netamount', 'netamt', 'finalamount', 'totalnet'], String(amount + loadingCharges - commission - tds - shortage))) || (amount + loadingCharges - commission - tds - shortage);
    const chequeAmount = parseFloat(findValue(['chequeamount', 'chequeamt', 'paidamount', 'recamount'], '0')) || 0;
    
    const paymentDateRaw = findValue(['paymentdate', 'paiddate', 'cleareddate'], '');
    const paymentDate = paymentDateRaw ? new Date(paymentDateRaw).toISOString().split('T')[0] : '';
    const bank = String(findValue(['bank', 'paymentbank', 'chequebank'], '')).trim();
    
    // Status Resolution
    const rawStatus = String(findValue(['paymentstatus', 'status'], '')).trim().toLowerCase();
    const paymentStatus: 'Cleared' | 'Pending' = (rawStatus.includes('clear') || rawStatus.includes('paid') || chequeAmount >= netAmount * 0.95 || paymentReceivedDays > 0)
      ? 'Cleared'
      : 'Pending';

    return {
      id: `TXN-${Date.now()}-${index}`,
      date: dateFormatted,
      millerName,
      placeArea,
      millerPlace,
      buyerArea,
      place: millerPlace,
      area: buyerArea,
      brand,
      buyerName,
      numberOfDays,
      paymentReceivedDays,
      billNumber,
      quantity,
      rate,
      amount,
      loadingCharges,
      commission,
      tds,
      shortage,
      seller,
      difference,
      netAmount,
      chequeAmount,
      paymentDate,
      bank,
      paymentStatus
    };
  });
}

