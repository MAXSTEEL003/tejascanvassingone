// Helper to extract the month name and year label
export function getMonthYearLabel(dateStr: string): string {
  if (!dateStr) return "MT (Current Month)";
  const parsed = parseAnyDate(dateStr);
  if (!parsed) return "MT (Current Month)";
  const monthNames = [
    "JANUARY", "FEBRUARY", "MARCH", "APRIL", "MAY", "JUNE",
    "JULY", "AUGUST", "SEPTEMBER", "OCTOBER", "NOVEMBER", "DECEMBER"
  ];
  const mName = monthNames[parsed.getMonth()] || "MT";
  return `${mName}-${parsed.getFullYear()}`;
}

