export function parseAnyDate(d: any): Date | null {
  if (!d) return null;
  if (d instanceof Date) return isNaN(d.getTime()) ? null : d;
  
  if (typeof d === 'number') {
    // Excel serial number offset
    const excelEpoch = new Date(1899, 11, 30);
    const date = new Date(excelEpoch.getTime() + d * 86400000);
    return isNaN(date.getTime()) ? null : date;
  }

  const str = String(d).trim();
  if (!str) return null;

  // Handle YYYY-MM-DD or YYYY/MM/DD
  if (/^\d{4}[-\/]\d{1,2}[-\/]\d{1,2}/.test(str)) {
    const parts = str.split(/[-\/]/);
    const y = parseInt(parts[0], 10);
    const m = parseInt(parts[1], 10) - 1;
    const day = parseInt(parts[2], 10);
    const date = new Date(y, m, day);
    return isNaN(date.getTime()) ? null : date;
  }

  // Handle DD-MM-YYYY or DD/MM/YYYY
  if (/^\d{1,2}[-\/]\d{1,2}[-\/]\d{2,4}/.test(str)) {
    const parts = str.split(/[-\/]/);
    const day = parseInt(parts[0], 10);
    const m = parseInt(parts[1], 10) - 1;
    let y = parseInt(parts[2], 10);
    if (y < 100) y += 2000;
    const date = new Date(y, m, day);
    return isNaN(date.getTime()) ? null : date;
  }

  // Standard string parse
  const parsed = new Date(str);
  return isNaN(parsed.getTime()) ? null : parsed;
}

export function formatDateToISO(d: any): string {
  const parsed = parseAnyDate(d);
  if (!parsed) return new Date().toISOString().split('T')[0];
  const yyyy = parsed.getFullYear();
  const mm = String(parsed.getMonth() + 1).padStart(2, '0');
  const dd = String(parsed.getDate()).padStart(2, '0');
  return `${yyyy}-${mm}-${dd}`;
}

function formatINR(val: number): string {
  if (isNaN(val)) return '0';
  return new Intl.NumberFormat('en-IN', {
    maximumFractionDigits: 0
  }).format(val);
}

